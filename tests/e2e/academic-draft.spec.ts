import { createClient } from '@supabase/supabase-js';
import { expect, test } from '@playwright/test';
import { academicCredential } from './e2eSupport';
import { openAcademicPage } from './academicFlowSupport';
import { loadAuthorizedContexts, toCommandContext } from '../../src/features/context/contextApi';
import { listPositions, loadPositionDetail, saveDraft } from '../../src/features/submission/positionApi';
test.use({ trace: 'off' });
test.skip(!process.env.ACADEMIC_CAM_EMAIL, 'Requires isolated academic fixture');
test('real academic area saves exact draft and origin across reload; context changes clear editing', async ({ page }) => {
    await page.goto('/');
    await page.getByLabel('E-mail').fill(academicCredential('area_tecnica').email);
    await page.getByLabel('Senha').fill(academicCredential('area_tecnica').password);
    await page.getByRole('button', { name: 'Entrar', exact: true }).click();
    const picker = page.getByLabel('Contexto autorizado');
    const option = picker.locator('option').filter({ hasText: 'ACADEMIC-NORTE-1 · ACADEMIC-2026-10' });
    await expect(option).toHaveCount(1);
    const key = (await option.getAttribute('value'))!;
    await picker.selectOption(key);
    await openAcademicPage(page, 'Preenchimento');
    await page.getByRole('button', { name: /ACADEMIC-NORTE-1 · ausente/ }).click();
    await page.getByLabel('Valor', { exact: true }).fill('0,0001');
    await page.getByLabel('Fonte', { exact: true }).fill('Origem sintética T05');
    await page.getByLabel('Período da fonte').fill('2026-10-01');
    await page.getByRole('button', { name: 'Salvar rascunho' }).click();
    await expect(page.getByText('Rascunho salvo. Ainda não enviado.')).toBeVisible();
    await page.reload();
    await picker.selectOption(key);
    await page.getByRole('button', { name: /ACADEMIC-NORTE-1 · rascunho/ }).click();
    await expect(page.getByLabel('Valor', { exact: true })).toHaveValue('0.0001');
    await expect(page.getByLabel('Fonte', { exact: true })).toHaveValue('Origem sintética T05');
    await page.getByLabel('Valor', { exact: true }).fill('1.234,56');
    await page.getByRole('button', { name: 'Salvar rascunho' }).click();
    await expect(page.getByRole('alert')).toBeVisible();
    await expect(page.getByLabel('Valor', { exact: true })).toHaveValue('1.234,56');
    const september = await picker.locator('option').filter({ hasText: 'ACADEMIC-NORTE-1 · ACADEMIC-2026-09' }).getAttribute('value');
    page.once('dialog', async (dialog) => {
        expect(dialog.type()).toBe('confirm');
        expect(dialog.message()).toContain('alterações não salvas');
        await dialog.dismiss();
    });
    await picker.selectOption(september!);
    await expect(page.getByLabel('Valor', { exact: true })).toHaveValue('1.234,56');
    await expect(picker).toHaveValue(key);
    page.once('dialog', async (dialog) => {
        expect(dialog.type()).toBe('confirm');
        expect(dialog.message()).toContain('alterações não salvas');
        await dialog.accept();
    });
    await picker.selectOption(september!);
    await expect(page.getByLabel('Valor', { exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: /ACADEMIC-NORTE-1 · ausente/ }).click();
    await expect(page.getByLabel('Fonte', { exact: true })).toHaveValue('');
});
test('real concurrent duplicate save is atomic and manager cannot read draft', async () => {
    const client = createClient(process.env.VITE_SUPABASE_URL!, process.env.VITE_SUPABASE_PUBLISHABLE_KEY!, { auth: { persistSession: false, autoRefreshToken: false } });
    expect((await client.auth.signInWithPassword(academicCredential('area_tecnica'))).error).toBeNull();
    const context = (await loadAuthorizedContexts(client)).find(c => c.competenciaCodigo === 'ACADEMIC-2026-10' && c.escopoCodigo === 'ACADEMIC-NORTE-2')!;
    const command = toCommandContext(context);
    const position = (await listPositions(client, command, { page: 1, pageSize: 25 })).items[0];
    const input = { estadoDado: 'valor' as const, valor: '99999999.9999', fonte: 'parallel synthetic', periodoFonte: '2026-10-01', motivo: '' };
    const id = crypto.randomUUID();
    const receipts = await Promise.all([saveDraft(client, command, position.id, position.version, input, id), saveDraft(client, command, position.id, position.version, input, id)]);
    expect(receipts[0]).toEqual(receipts[1]);
    expect(receipts[0].version).toBe(2);
    const detail = await loadPositionDetail(client, command, position.id);
    expect(detail.revisions).toHaveLength(1);
    expect(detail.revisions[0].value).toBe('99999999.9999');
    expect(detail.memories).toEqual([]);
    await expect(saveDraft(client, command, position.id, 1, { ...input, valor: '0' }, id)).rejects.toMatchObject({ code: 'operation_payload_mismatch' });
    await expect(saveDraft(client, command, position.id, 1, input, crypto.randomUUID())).rejects.toMatchObject({ code: 'version_conflict' });
    await client.auth.signOut();
    expect((await client.auth.signInWithPassword(academicCredential('gestor_unidade'))).error).toBeNull();
    const manager = (await loadAuthorizedContexts(client)).find(c => c.competenciaCodigo === 'ACADEMIC-2026-10')!;
    await expect(loadPositionDetail(client, toCommandContext(manager), position.id)).rejects.toMatchObject({ code: '42501' });
    await expect(saveDraft(client, toCommandContext(manager), position.id, 2, input, crypto.randomUUID())).rejects.toMatchObject({ code: 'access_denied' });
    await client.auth.signOut();
});
